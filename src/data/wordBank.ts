// Fallback helper for legacy storage
export function normalizeDifficulty(diff: string): DifficultyLevel {
  if (diff === 'apprentice') return 'basic_foundation';
  if (diff === 'adventurer' || diff === 'master') return 'ssc_exams';
  if (diff === 'legendary') return 'banking_po';
  if (
    diff === 'basic_foundation' ||
    diff === 'college_entry' ||
    diff === 'college_placement' ||
    diff === 'ssc_exams' ||
    diff === 'ssc_chsl' ||
    diff === 'ssc_cgl' ||
    diff === 'banking_po' ||
    diff === 'gate_aptitude' ||
    diff === 'defence_cds' ||
    diff === 'ielts_clat' ||
    diff === 'cat_upsc'
  ) {
    return diff;
  }
  return 'ssc_exams';
}

